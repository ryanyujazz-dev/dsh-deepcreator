/**
 * Verify the materialized preset against the stamp; a missing, drifted, or
 * tampered preset is re-materialized and reported.
 * @param presetsRoot - Absolute `.agent-presets` directory.
 * @param log - Warning sink (tamper/drift reports).
 * @returns what happened, for boot diagnostics.
 */
export async function ensurePreset(presetsRoot: string, log: (message: string) => void): Promise<'materialized' | 'verified' | 'healed'> {
  const dir = join(presetsRoot, APP_STAGE_PRESET_ID)
  const compositionPath = join(dir, 'agent.cordis.yml')
  const metadataPath = join(dir, 'preset.yml')
  const stampPath = join(dir, STAMP_FILE)
  const skillsDir = join(dir, 'skills')

  const agentUrl = agentEntryUrl()
  const agentDigest = await digestFile(fileURLToPath(agentUrl))
  const composition = compositionFor(agentUrl)
  const stamp: PresetStamp = {
    generator: GENERATOR_VERSION,
    agentEntry: agentUrl,
    agentDigest,
    compositionDigest: digest(new TextEncoder().encode(composition)),
    skillsDigest: digestSkills(),
  }

  const existing = await readJson(stampPath) as Partial<PresetStamp> | undefined
  if (existing === undefined || existing.generator !== GENERATOR_VERSION || existing.agentEntry !== agentUrl || existing.agentDigest !== agentDigest || existing.skillsDigest !== stamp.skillsDigest) {
    if (existing !== undefined) log(`app-stage preset stamp mismatch (agent entry, generator, or skills drifted) — re-materializing ${dir}`)
    await materialize(dir, compositionPath, composition, metadataPath, metadataFor(), stampPath, stamp, skillsDir)
    return 'materialized'
  }
  const onDisk = await readFile(compositionPath, 'utf8').catch(() => undefined)
  if (onDisk === undefined || digest(new TextEncoder().encode(onDisk)) !== existing.compositionDigest) {
    log(`app-stage preset composition tampered or corrupted — re-materializing ${compositionPath}`)
    await materialize(dir, compositionPath, composition, metadataPath, metadataFor(), stampPath, stamp, skillsDir)
    return 'healed'
  }
  return 'verified'
}

async function materialize(dir: string, compositionPath: string, composition: string, metadataPath: string, metadata: string, stampPath: string, stamp: PresetStamp, skillsDir: string): Promise<void> {
  await mkdir(dir, { recursive: true })
  await writeFile(compositionPath, composition, 'utf8')
  await writeFile(metadataPath, metadata, 'utf8')
  await writeFile(stampPath, `${JSON.stringify(stamp, null, 2)}\n`, 'utf8')
  for (const [relative, body] of Object.entries(APP_STAGE_SKILLS)) {
    const file = join(skillsDir, relative)
    await mkdir(dirname(file), { recursive: true })
    await writeFile(file, body, 'utf8')
  }
}

/** Combined digest of every carried skill file (order-stable). */
function digestSkills(): string {
  const parts = Object.keys(APP_STAGE_SKILLS).sort().map(key => `${key}:${digest(new TextEncoder().encode(APP_STAGE_SKILLS[key]!))}`)
  return digest(new TextEncoder().encode(parts.join('\n')))
}

async function digestFile(path: string): Promise<string> {
  const bytes = await readFile(path).catch(() => new Uint8Array())
  return digest(bytes)
}

async function readJson(path: string): Promise<unknown> {
  try {
    return JSON.parse(await readFile(path, 'utf8')) as unknown
  } catch {
    return undefined
  }
}

/** Generated-preset paths (diagnostics and tests). */
export const presetDirectory = (presetsRoot: string): string => join(presetsRoot, APP_STAGE_PRESET_ID)
export const presetStampPath = (presetsRoot: string): string => join(presetDirectory(presetsRoot), STAMP_FILE)
export const presetCompositionPath = (presetsRoot: string): string => join(presetDirectory(presetsRoot), 'agent.cordis.yml')
