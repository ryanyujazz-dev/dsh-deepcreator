/**
 * The app-stage agent-preset materializer.
 *
 * The `app-stage-agent` plugin row exists ONLY inside the preset composition
 * (tool availability is permission); it is never a bundle row. This module
 * materializes that preset under `$DSH_HOME/.agent-presets/app-stage/`:
 *
 * - `agent.cordis.yml` — the standard agent toolset (shell, files, search,
 *   skills, goals, plan mode, compaction, delegation, ask/todo/web) plus the
 *   `file:` URL row loading the built agent package and the app-stage persona
 *   (a session that cannot write files cannot develop apps).
 * - `skills/` — the preset-carried `app-dev` and `workstage-use` skills.
 * - `preset.yml` — display metadata.
 * - `.deepcreator-stamp.json` — generator version, agent entry, and digests
 *   of every generated file, so a tampered or drifted preset is detected on
 *   boot, warned about loudly, and re-materialized (the preset is generated
 *   property, not user data).
 * @module @ryanyujazz/dsh-app-stage/preset
 */
import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { join, dirname } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { APP_STAGE_SKILLS } from './preset-skills.ts'

/** Preset id — also the directory name under `.agent-presets/`. */
export const APP_STAGE_PRESET_ID = 'app-stage'

/** Stamp file name (generated-property marker; not part of the preset contract). */
const STAMP_FILE = '.deepcreator-stamp.json'

interface PresetStamp {
  readonly generator: number
  readonly agentEntry: string
  readonly agentDigest: string
  readonly compositionDigest: string
  readonly skillsDigest: string
}

/** Bump when the generated files' shape changes (drifted stamps re-materialize). */
const GENERATOR_VERSION = 3

const digest = (bytes: Uint8Array): string => createHash('sha256').update(bytes).digest('hex')
const nodeRequire = createRequire(import.meta.url)

/**
 * Resolve the built agent-package entry as a `file:` URL (S5 form).
 * Resolution walks the package dependency edge, so the answer follows the
 * installation (repo checkout under link: deps, node_modules in a packaged
 * install) instead of hard-coding a path.
 */
export function agentEntryUrl(): string {
  return pathToFileURL(nodeRequire.resolve('@ryanyujazz/dsh-app-stage-agent')).href
}

