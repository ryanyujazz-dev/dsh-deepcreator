import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const packageJsonPath = require.resolve('material-icon-theme/package.json')
const packageRoot = dirname(packageJsonPath)
const packageJson = JSON.parse(readFileSync(packageJsonPath, 'utf8'))
const manifest = JSON.parse(readFileSync(join(packageRoot, 'dist/material-icons.json'), 'utf8'))

function normalizedRecord(record = {}) {
  return Object.fromEntries(
    Object.entries(record)
      .map(([key, value]) => [key.replaceAll('\\', '/').toLowerCase(), value])
      .sort(([left], [right]) => left.localeCompare(right)),
  )
}

const fileNames = normalizedRecord(manifest.fileNames)
const fileExtensions = normalizedRecord(manifest.fileExtensions)
const lightFileNames = normalizedRecord(manifest.light?.fileNames)
const lightFileExtensions = normalizedRecord(manifest.light?.fileExtensions)
const iconIds = new Set([
  manifest.file,
  ...Object.values(fileNames),
  ...Object.values(fileExtensions),
  ...Object.values(lightFileNames),
  ...Object.values(lightFileExtensions),
])

const iconSources = {}
for (const iconId of [...iconIds].sort()) {
  const definition = manifest.iconDefinitions?.[iconId]
  if (typeof definition?.iconPath !== 'string') {
    throw new Error(`Material Icon Theme is missing icon definition: ${iconId}`)
  }
  const iconPath = resolve(packageRoot, 'dist', definition.iconPath)
  const svg = readFileSync(iconPath, 'utf8').trim()
  if (!svg.startsWith('<svg') || !svg.endsWith('</svg>')) {
    throw new Error(`Material Icon Theme asset is not an SVG document: ${iconPath}`)
  }
  if (/<script\b|\son\w+\s*=|(?:href|src)\s*=\s*["'](?:https?:|javascript:)/iu.test(svg)) {
    throw new Error(`Material Icon Theme asset contains disallowed active content: ${iconPath}`)
  }
  iconSources[iconId] = `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`
}

const output = `/* eslint-disable */
// Generated by scripts/generate-file-icons.mjs from Material Icon Theme ${packageJson.version}.
// Do not edit by hand; the checked-in output keeps clean installs deterministic.

export const MATERIAL_ICON_THEME_VERSION = ${JSON.stringify(packageJson.version)}
export const DEFAULT_FILE_ICON = ${JSON.stringify(manifest.file)}
export const FILE_NAME_ICONS: Readonly<Record<string, string>> = ${JSON.stringify(fileNames, null, 2)}
export const FILE_EXTENSION_ICONS: Readonly<Record<string, string>> = ${JSON.stringify(fileExtensions, null, 2)}
export const LIGHT_FILE_NAME_ICONS: Readonly<Record<string, string>> = ${JSON.stringify(lightFileNames, null, 2)}
export const LIGHT_FILE_EXTENSION_ICONS: Readonly<Record<string, string>> = ${JSON.stringify(lightFileExtensions, null, 2)}
export const FILE_ICON_SOURCES: Readonly<Record<string, string>> = ${JSON.stringify(iconSources, null, 2)}
`

const target = fileURLToPath(new URL('../src/file-icons/generated.ts', import.meta.url))
writeFileSync(target, output)
